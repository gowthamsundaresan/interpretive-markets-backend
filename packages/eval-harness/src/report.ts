import type { AgreementReport } from './judge-validation/validate'
import type { CalibrationReport } from './scorers/judge/calibration'
import type { RunReport, ScorerResult } from './types'
import type { VersionDiff } from './version-diff'

// --- Types & state ---

export interface RenderArgs {
	report: RunReport
	agreement: AgreementReport
	calibration: CalibrationReport
	versionDiff: VersionDiff
	baselineFailures: { caseId: string; scorer: string; detail: string }[]
	providerRequested: 'mock' | 'llm' | 'ritual-l1'
}

// --- Core functions ---

export function renderReport(args: RenderArgs): string {
	const { report, agreement, calibration, versionDiff, baselineFailures, providerRequested } = args
	const { meta, caseCount, results } = report
	const counts = counts_(results)
	const byScorer = groupByScorer(results)

	return [
		'# Interpretive Markets — Eval Report',
		'',
		`> Generated ${meta.finishedAt} (suite=${meta.suite}, provider=${providerRequested}, ${meta.durationMs}ms over ${caseCount} cases)`,
		'',
		'## Headline numbers',
		'',
		`- **Cases evaluated:** ${caseCount}`,
		`- **Total scorer runs:** ${results.length}`,
		`- **Pass / Fail / Skipped:** ${counts.pass} / ${counts.fail} / ${counts.skipped}`,
		renderECE(calibration),
		renderAgreement(agreement),
		'',
		'## Scorer breakdown',
		'',
		'| Scorer | Pass | Fail | Skipped |',
		'| --- | ---: | ---: | ---: |',
		...Object.entries(byScorer)
			.sort(([a], [b]) => a.localeCompare(b))
			.map(([name, rs]) => {
				const c = counts_(rs)
				return `| \`${name}\` | ${c.pass} | ${c.fail} | ${c.skipped} |`
			}),
		'',
		'## Baseline failures (untuned)',
		'',
		baselineFailures.length === 0
			? '_No failures in this run._'
			: [
					'_These are the actual failure modes observed — not tuned for green. Each one is a real signal about either judge capability or the case shape._',
					'',
					...baselineFailures.map((f) => `- **${f.scorer}** @ \`${f.caseId}\` — ${f.detail}`)
				].join('\n'),
		'',
		'## Calibration (Expected Calibration Error)',
		'',
		renderCalibration(calibration, providerRequested),
		'',
		'## Hand-labelled cases',
		'',
		renderHumanLabels(agreement, providerRequested),
		'',
		'## Version diff',
		'',
		renderVersionDiff(versionDiff),
		'',
		'## Cost + latency',
		'',
		`- **Total wall-clock:** ${meta.durationMs}ms`,
		`- **Cost-per-resolution:** _not measured (provider=${providerRequested}; on-chain measurement gated on Phase 0.5 testnet probe)_`,
		`- **Latency distribution:** _not measured (need ≥30 cases × multiple providers)_`,
		'',
		'---',
		'_Generated by `packages/eval-harness/src/runner.ts`. Re-run with mock: `npm run eval --workspace @interpretive/eval-harness -- --suite=all --provider=mock`. Re-run with real LLM: `ANTHROPIC_API_KEY=... npm run eval --workspace @interpretive/eval-harness -- --suite=all --provider=llm`._',
		''
	].join('\n')
}

// --- Helper functions ---

function renderECE(calibration: CalibrationReport): string {
	if (calibration.casesWithGroundTruth === 0) {
		return '- **ECE:** _no ground-truth verdicts to calibrate against in this run_'
	}
	return `- **Expected Calibration Error (ECE):** ${calibration.ece.toFixed(4)} over ${calibration.casesWithGroundTruth} cases (max bucket gap ${calibration.maxCalibrationError.toFixed(4)})`
}

function renderAgreement(agreement: AgreementReport): string {
	if (agreement.totalLabelledCases === 0) {
		return `- **Judge-vs-human:** _awaiting human review — ${agreement.totalProposedCases} model proposals stored in \`judge-validation/human-labels.json\`, no humanVerdict slots populated yet_`
	}
	return [
		`- **Judge-vs-human outcome agreement:** ${pct(agreement.outcomeAgreement)} (${agreement.totalLabelledCases} hand-labelled, ${agreement.totalProposedCases} proposals total)`,
		`- **Judge-vs-human driving-tier agreement:** ${pct(agreement.tierAgreement)}`,
		`- **Mean confidence delta (judge vs human):** ${agreement.meanConfidenceDeltaBps.toFixed(0)} bps`
	].join('\n')
}

function renderCalibration(
	calibration: CalibrationReport,
	providerRequested: 'mock' | 'llm' | 'ritual-l1'
): string {
	if (calibration.casesWithGroundTruth === 0) {
		return '_No ground-truth outcomes available for calibration — run with `--provider=llm` against cases with `expectedFinalOutcome`._'
	}
	const provider =
		providerRequested === 'mock'
			? '`mock` provider — tautological by construction; reported for sanity only'
			: `\`${providerRequested}\` provider`
	const populated = calibration.buckets.filter((b) => b.count > 0)
	if (populated.length === 0) return '_No populated buckets._'
	const header = [
		'| Confidence bucket (bps) | Cases | Mean confidence | Empirical accuracy | Gap |',
		'| --- | ---: | ---: | ---: | ---: |'
	]
	const rows = populated.map(
		(b) =>
			`| ${b.rangeStart}-${b.rangeEnd} | ${b.count} | ${b.meanConfidence.toFixed(0)} | ${(b.empiricalAccuracy * 100).toFixed(1)}% | ${b.gap.toFixed(4)} |`
	)
	return [
		`Provider: ${provider}.`,
		'',
		`ECE = ${calibration.ece.toFixed(4)}, max bucket gap = ${calibration.maxCalibrationError.toFixed(4)}.`,
		'',
		...header,
		...rows
	].join('\n')
}

function renderHumanLabels(
	agreement: AgreementReport,
	providerRequested: 'mock' | 'llm' | 'ritual-l1'
): string {
	if (agreement.totalLabelledCases === 0 && agreement.totalProposedCases === 0) {
		return providerRequested === 'llm'
			? '_LLM provider ran but no proposals were stored. Check `judge-validation/human-labels.json`._'
			: '_No model proposals stored. Run with `--provider=llm` to populate the proposal slots; then human-review the proposals tomorrow._'
	}
	if (agreement.totalLabelledCases === 0) {
		return [
			`_${agreement.totalProposedCases} blind model proposals are stored in \`judge-validation/human-labels.json\`. Each entry has \`status: "awaiting-human-review"\`, a \`proposedVerdict\`, and an empty \`humanVerdict\` slot. Until the human review pass populates \`humanVerdict\`, no judge-vs-human agreement number is reported._`,
			'',
			'_Review workflow: open the JSON, read the model\'s proposal + rationale, decide on the correct verdict, fill `humanVerdict` + `humanReasoning` + `labelledBy` + `labelledAt`, flip `status` to `"labelled"`._'
		].join('\n')
	}
	return agreement.cases
		.map(
			(c) =>
				`- \`${c.caseId}\` — outcome match: ${c.outcomeMatch ? '✓' : '✗'}, subject match: ${c.subjectMatch ? '✓' : '✗'}, tier match: ${c.drivingTierMatch ? '✓' : '✗'}, |Δconfidence|: ${c.confidenceBpsDelta} bps`
		)
		.join('\n')
}

function renderVersionDiff(diff: VersionDiff): string {
	if (!diff.hasPrevious) {
		return '_No previous snapshot to diff against — this is the baseline run. Subsequent runs will populate this section._'
	}
	const lines: string[] = []
	lines.push(`_Previous snapshot: ${diff.previousGeneratedAt}._`)
	lines.push('')
	lines.push('| Metric | Previous | Current |')
	lines.push('| --- | --- | --- |')
	for (const h of diff.headlineDeltas) {
		lines.push(`| ${h.metric} | ${h.previous} | ${h.current} |`)
	}
	lines.push('')
	lines.push('| Scorer | Prev pass / fail / skip | Cur pass / fail / skip | Δpass | Δfail |')
	lines.push('| --- | --- | --- | ---: | ---: |')
	for (const d of diff.deltas) {
		const prev = `${d.previous.pass} / ${d.previous.fail} / ${d.previous.skipped}`
		const cur = `${d.current.pass} / ${d.current.fail} / ${d.current.skipped}`
		const passSign = d.passDelta > 0 ? '+' : ''
		const failSign = d.failDelta > 0 ? '+' : ''
		lines.push(
			`| \`${d.scorer}\` | ${prev} | ${cur} | ${passSign}${d.passDelta} | ${failSign}${d.failDelta} |`
		)
	}
	return lines.join('\n')
}

function counts_(results: ScorerResult[]): { pass: number; fail: number; skipped: number } {
	return {
		pass: results.filter((r) => r.outcome === 'pass').length,
		fail: results.filter((r) => r.outcome === 'fail').length,
		skipped: results.filter((r) => r.outcome === 'skipped').length
	}
}

function groupByScorer(results: ScorerResult[]): Record<string, ScorerResult[]> {
	const out: Record<string, ScorerResult[]> = {}
	for (const r of results) {
		if (!out[r.scorer]) out[r.scorer] = []
		out[r.scorer].push(r)
	}
	return out
}

function pct(n: number): string {
	if (Number.isNaN(n)) return '—'
	return `${(n * 100).toFixed(1)}%`
}
